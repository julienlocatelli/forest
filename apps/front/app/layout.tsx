import type { Metadata } from "next";
import { themeStylesheet } from "@forest/design-tokens";
import { applyStoredTheme } from "./theme";
import { ThemeSelector } from "./theme-selector";
import { Geist, Geist_Mono } from "next/font/google";
import "@forest/ui/styles.css";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      // The head script sets data-theme before React hydrates.
      suppressHydrationWarning
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: applyStoredTheme }} />
        {/* Every shared theme: light by default, dark when the system prefers it, or the chosen data-theme. */}
        <style dangerouslySetInnerHTML={{ __html: themeStylesheet() }} />
      </head>
      <body className="min-h-full flex flex-col">
        <header className="flex justify-end px-(--space-lg) py-(--space-sm)">
          <ThemeSelector />
        </header>
        {children}
      </body>
    </html>
  );
}
